"""Generate auditable, narrowly scoped derivatives of the frozen Best."""
from pathlib import Path
import hashlib
ROOT=Path(__file__).resolve().parents[1]
BASE_SHA='2cd6440fb6e78a406a9abac1cab642a98ec94bd07f46f2e55f641d04a23ae1db'

def source(mixed=False,core=False):
    base=(ROOT/'MySpillSchedulerBest.cpp').read_text()
    assert hashlib.sha256(base.encode()).hexdigest()==BASE_SHA
    extra='''
    // Sources: periodic=1, after-miss-next=2. Current miss is deliberately excluded.
    std::vector<double> sample_count_;
    std::vector<int64_t> periodic_count_, after_miss_count_;
    double sample_total_=0;
    int64_t sample_q_=-1;
    int sample_sources_=0;
    std::vector<bool> core_;
    void sampleNext(const SystemState& s,int source) {
        if(s.next_op.type!="PROBE" || s.next_op.op_id<0 ||
           s.next_op.op_id>=static_cast<int>(s.operators.size()))return;
        const int id=s.next_op.op_id*p_+static_cast<int>(s.next_op.key%p_);
        const int64_t q=s.hit_count+s.miss_count+1;
        if(q!=sample_q_) {sample_q_=q;sample_sources_=0;}
        if(sample_sources_&source)return;
        if(source==1)++periodic_count_[id]; else ++after_miss_count_[id];
        const bool accepted=ACCEPT;
        const bool already=ALREADY;
        if(accepted && !already) {++sample_count_[id];++sample_total_;}
        sample_sources_|=source;
    }
    double probability(int id) const {
        return (sample_count_[id]+64.0/sample_count_.size())/(sample_total_+64.0);
    }
    void refreshCore(const SystemState& s) {
        struct Item {int id;int64_t size;double density;};
        std::vector<Item> items;std::vector<int64_t> sizes;
        for(const auto& o:s.operators) for(const auto& x:o.partitions) {
            if(o.phase!=Phase::PROBE || x.data_size<=0)continue;
            int id=o.op_id*p_+x.partition_id;
            double d=probability(id)*(1.0/s.read_bandwidth+1.0/s.write_bandwidth+1.0/x.data_size);
            items.push_back({id,x.data_size,d*(core_[id]?1.1:1.0)});
            sizes.push_back(x.data_size);
        }
        if(sizes.empty())return;
        std::sort(sizes.begin(),sizes.end());
        // Upper median object size is a soft working-space proxy, not empty memory.
        int64_t budget=std::max<int64_t>(0,s.memory_limit-sizes[sizes.size()/2]);
        std::sort(items.begin(),items.end(),[](const Item& a,const Item& b){
            return a.density!=b.density?a.density>b.density:a.id<b.id;
        });
        std::fill(core_.begin(),core_.end(),false);
        for(const auto& x:items)if(x.size<=budget){core_[x.id]=true;budget-=x.size;}
    }
'''.replace('ACCEPT','true' if mixed else 'source==1').replace('ALREADY','sample_sources_!=0' if mixed else '(sample_sources_&1)!=0')
    base=base.replace('    void observe(',extra+'    void observe(',1)
    marker='            p_ = s.num_partitions; history_.assign(n, History{});'
    base=base.replace(marker,marker+'\n            sample_count_.assign(n,0);periodic_count_.assign(n,0);after_miss_count_.assign(n,0);\n            core_.assign(n,false);sample_total_=0;sample_q_=-1;sample_sources_=0;')
    marker='            // The true penalty is absent'
    replacement='''            // A 64-request retention horizon fixes the scale against immediate write cost.
            // This is a proxy, not a claim of unbiased estimates for correlated requests.
            if(o.phase==Phase::PROBE && !scan) {
                reuse=std::min(1.0,64.0*probability(o.op_id*p_+part.partition_id));
            }
'''
    base=base.replace(marker,replacement+marker)
    if core:
        base=base.replace('        victims_.clear();','        refreshCore(s);\n        victims_.clear();')
        base=base.replace('            if (o.op_id == next_op && part.partition_id == next_pid) priority += 1e12;',
            '            if(core_[o.op_id*p_+part.partition_id]) priority*=2.0;\n            if (o.op_id == next_op && part.partition_id == next_pid) priority += 1e12;')
    base=base.replace('active_ = true; update(s,op,pid);','active_ = true; update(s,op,pid); sampleNext(s,2);')
    base=base.replace('        if (!active_) return a;\n        update(s);','        update(s); sampleNext(s,1);\n        if (!active_) return a;')
    return '// Round7 experimental derivative; generated by make_candidates.py.\n'+base

if __name__=='__main__':
    for name,mixed,core in [('periodic64',False,False),('mixed64',True,False),('mixed64_core',True,True)]:
        path=ROOT/'round7'/(name+'.cpp');text=source(mixed,core)
        if path.exists():assert path.read_text()==text
        else:path.write_text(text)
